# ================================
# 20. Simple turbine power curve
# ================================

def turbine_power_curve(
    wind_speed,
    rated_power=2000,
    cut_in=3,
    rated_speed=12,
    cut_out=25
):

    power = np.zeros_like(wind_speed)

    # Between cut-in and rated speed
    rising = (
        (wind_speed >= cut_in)
        & (wind_speed < rated_speed)
    )

    power[rising] = (
        rated_power
        * (
            (wind_speed[rising] - cut_in)
            / (rated_speed - cut_in)
        ) ** 3
    )

    # Rated power region
    rated = (
        (wind_speed >= rated_speed)
        & (wind_speed <= cut_out)
    )

    power[rated] = rated_power

    return power

