# ================================
# 24. Hub-height sensitivity
# ================================

reference_height = 100
alpha = 0.14

hub_heights = [50, 80, 100, 120]

results = []

for height in hub_heights:

    scale_factor = (
        height / reference_height
    ) ** alpha

    adjusted_scale = c * scale_factor

    pdf = weibull_min.pdf(
        wind_range,
        k,
        loc=0,
        scale=adjusted_scale
    )

    power_curve = turbine_power_curve(
        wind_range,
        rated_power=2000
    )

    mean_power = trapezoid(
        power_curve * pdf,
        wind_range
    )

    AEP = (
        mean_power
        * hours_per_year
        / 1000
    )

    CF = mean_power / rated_power

    results.append({
        "Hub height (m)": height,
        "Mean wind speed (m/s)": (
            adjusted_scale
            * gamma(1 + 1 / k)
        ),
        "Mean power (kW)": mean_power,
        "AEP (MWh/year)": AEP,
        "Capacity factor (%)": CF * 100
    })

results_df = pd.DataFrame(results)

display(results_df.round(2))

